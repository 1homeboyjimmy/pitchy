_TEMPLATES_BY_KEY = {
    GENERIC_TEMPLATE["key"]: GENERIC_TEMPLATE,
    FSI_STUDSTARTUP_TEMPLATE["key"]: FSI_STUDSTARTUP_TEMPLATE,
}


def _grant_get(grant, field: str):
    return grant.get(field) if isinstance(grant, dict) else getattr(grant, field, None)


def select_application_template(grant) -> dict:
    """Выбор шаблона заявки для гранта:
      1) явный grant.application_template (правится админом);
      2) совпадение по названию/организации (ФСИ «Студенческий стартап»);
      3) универсальный дефолт.
    """
    override = _grant_get(grant, "application_template")
    if isinstance(override, dict) and override.get("groups"):
        return override

    name = (_grant_get(grant, "name") or "").lower()
    org = (_grant_get(grant, "organization") or "").lower()
    haystack = f"{name} {org}"
    if "студенческий стартап" in haystack or "студстартап" in haystack:
        return FSI_STUDSTARTUP_TEMPLATE

    return GENERIC_TEMPLATE


def template_by_key(key: str) -> dict | None:
    return _TEMPLATES_BY_KEY.get(key)
